        <h1 class="why-titre">La règle générale</h1>

        <figure class="regle">
          <figcaption class="regle-ref">Chapitre 1.8.3.1 de l’ADR 2021</figcaption>
          <blockquote>« Chaque entreprise dont les activités comprennent l'expédition ou le transport de marchandises dangereuses par route, ou les opérations connexes d'emballage, de chargement, de remplissage ou de déchargement, désigne un ou plusieurs conseillers à la sécurité, nommés ci-après "conseillers", pour le transport de marchandises dangereuses, chargés d'aider à la prévention des risques pour les personnes, les biens ou l'environnement, inhérents à ces activités. »</blockquote>
        </figure>

        <p class="remove-mb">Cela signifie que les donneurs d’ordre sont concernés même s’ils n’interviennent pas physiquement dans l’opération de chargement des matières dangereuses. Ainsi, une société qui expédie des matières dangereuses par le biais d’une plateforme logistique avec un prestataire est impactée par ce chapitre de l’ADR.</p>

        <div id="suite-why" class="display-while-clicking">
          <p>La mission du Conseiller Sécurité pour le Transport des Matières Dangereuses agit sous la responsabilité du Chef d'Entreprise et a pour missions essentielles :</p>
          <ol class="prestations">
            <li>Examiner le respect des prescriptions relatives au transport de marchandises dangereuses</li>
            <li>Conseiller l'entreprise dans les opérations concernant le transport de marchandises dangereuses</li>
            <li>Assurer la rédaction d'un rapport annuel sur les activités de l'entreprise</li>
          </ol>

          <h2 class="why-sous-titre">Les sanctions et les contrôles</h2>
          <p>Suite à une modification de la loi 92-125 du 6 février 1992 relative à la constatation et la répression des infractions en matière de transports publics et privés (loi n°2002-3 du 3 janvier 2002), la non-désignation d'un conseiller à la sécurité est considérée comme un délit, et passible, à ce titre, d'un mois à un an d'emprisonnement et d'une amende de 1000 à 30 000 euros. Les autres infractions (absences des équipements obligatoires, formation...) sont des contraventions de 5ème catégorie (amendes de 1500 euros maximum).</p>
          <p>Les contrôles des infractions peuvent être réalisés par les inspecteurs du ministère chargé des transports, les agents de douanes, les agents chargés de constater les infractions en matière de circulation routière, les inspecteurs du travail, etc. Les établissements peuvent être contrôlés aussi bien sur les lieux de chargement ou déchargement que sur la route.</p>
